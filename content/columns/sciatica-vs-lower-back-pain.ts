腰に負担が集まる身体の使い方が続くと、椎間板や関節への負担が増し、神経を刺激するようになることがあります。また、腰をかばうことでお尻や股関節の筋肉が硬くなり、その筋肉が坐骨神経を刺激するケースもあります。

腰痛の段階で身体の使い方を整えておくことは、神経の症状へ進むことを防ぐうえでも大切です。

