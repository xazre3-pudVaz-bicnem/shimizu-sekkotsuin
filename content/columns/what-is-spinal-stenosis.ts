医療機関では、まず薬（神経の血流を改善する薬や痛み止め）、神経ブロック、リハビリ、コルセットなどの保存療法が行われます。日常生活に大きな支障がある、歩ける距離が著しく短い、筋力低下や排尿障害が進んでいるといった場合には、脊柱管を広げる手術が検討されます。

手術の要否は医師が判断するものであり、症状の経過を医療機関で定期的に確認することが大切です。

