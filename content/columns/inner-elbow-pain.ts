ストレッチは、肘を伸ばし手のひらを上に向け、反対の手で指先を下へ引く方法があります。痛みが出ない範囲で、20秒ほどを目安にします。強く引きすぎないことが大切です。効果には個人差があります。

スポーツの場面では、用具やフォームの見直しも関わると考えられています。グリップの太さや、ボールを打つ位置も負担に影響するとされています。

