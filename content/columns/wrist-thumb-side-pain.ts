親指を繰り返し使ったり、手首を小指側に強く曲げたりする動きが続くと、腱と腱鞘のこすれが増えます。その結果、腱鞘が厚くなったり、腱がむくんだりして、すべりが悪くなることがあります。これが**腱鞘炎**と呼ばれる状態で、手首の親指側に起こるものは「ドケルバン病（狭窄性腱鞘炎）」と呼ばれています。

