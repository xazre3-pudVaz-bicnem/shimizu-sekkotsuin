- タオルをしぼる、ふたを開ける、ドアノブを回す動作がつらい
- 腫れぼったさや、動かすときの引っかかり感がある

ただし、手首の痛みの原因はこれだけではありません。関節そのものの問題や、骨の障害、神経の問題が関わっていることもあります。自己判断で決めつけず、状態を確認することが大切だと考えられています。

